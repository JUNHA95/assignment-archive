
"""
8교시 종합 실습

[전체 시스템 구조]
사용자 → FastAPI → PostgreSQL → 고정 스냅샷
       → Context 구성 → Prompt 조립 → LLM Client
       → 응답 검증 → 사람의 근거 검토 → 사용자

※ 위 구조는 수업에서 배운 전체 시스템 설계이다.
※ 이번 실습은 새로운 FastAPI·DB·RAG를 만들지 않는다.
※ 미리 준비된 질문과 지식을 사용해 LLM 처리 과정을 실행한다.

[공통 예시: 온라인 쇼핑몰 반품 문의]

사용자 질문:
"상품을 받은 지 10일이 지났는데 불량품이면 반품할 수 있나요?"

참고 규정:
"상품에 문제가 있으면 수령 후 7일이 지나도 반품할 수 있으며,
반품 배송비는 무료입니다."

목표:
AI가 위 규정을 근거로 질문에 답하고,
답변의 형식·출처·비용을 검사한 뒤 사람이 근거를 검토한다.
"""

from pathlib import Path
import sys


# ============================================================
# [0단계] 실행 환경 준비
# ============================================================
# 목적:
# 현재 파일에서 다른 폴더의 공통 기능을 불러올 수 있도록 준비한다.
#
# HERE: 현재 main.py가 들어 있는 폴더
# ROLE_ROOT: coursekit 공통 기능을 찾기 위한 상위 폴더
#
# 아직 API를 호출하지 않는다.

HERE = Path(__file__).resolve().parent
ROLE_ROOT = HERE.parents[1]
sys.path.insert(0, str(ROLE_ROOT))

from coursekit.support import parse_args, guarded, daily_project
from coursekit.metrics import summarize_runs
from coursekit.records import table_rows


# ============================================================
# [1단계] 실행할 질문 지정
# ============================================================
# 함수: project_cases()
#
# [목적]
# 이번 실습에서 처리할 질문을 순서대로 지정한다.
#
# [입력]
# 별도의 입력 없음
#
# [처리]
# H01, H02, H03이라는 질문 ID를 목록으로 만든다.
#
# 이 ID는 실제 질문 내용이 아니라 질문을 구분하는 이름이다.
# 실제 질문과 참고 지식은 이후 input_parts()에서 준비한다.
#
# [출력]
# ["H01", "H02", "H03"]
#
# 예시:
# 쇼핑몰에서 여러 고객 문의를 순서대로 처리하기 위해
# 각 문의에 번호를 붙이는 것과 비슷하다.
#
# [다음 단계]
# daily_project()가 이 목록을 받아 질문을 하나씩 처리한다.

def project_cases():
    return ["H01", "H02", "H03"]


# ============================================================
# [2단계] 질문별 실행 결과를 표로 정리
# ============================================================
# 함수: project_rows(runs)
#
# [목적]
# 각 질문의 실행 상태, 응답 시간, 토큰 사용량 등을
# 비교할 수 있도록 표 형태로 정리한다.
#
# [입력]
# runs: 각 질문의 실행 결과가 담긴 목록
#
# [처리]
# table_rows()가 실행 기록을 표의 각 행으로 변환한다.
#
# 예시:
# H01 → 정상 응답
# H02 → API 오류
# H03 → 앞선 오류로 실행하지 않음
#
# 정상 응답만 남기면 실제 오류 발생 여부를 알 수 없으므로
# 실패하거나 실행하지 않은 결과도 함께 기록한다.
#
# [오늘 배운 내용: 3교시·5교시]
#
# - request_ms:
#   API 요청 처리에 걸린 시간
#
# - first_text_ms:
#   요청 후 첫 텍스트가 도착하기까지 걸린 시간(TTFT)
#
# - input_tokens:
#   AI에 전달된 전체 입력 토큰 수
#
# - cached_tokens:
#   입력 토큰 중 이전 계산이 재사용된 부분
#
# - output_tokens:
#   AI가 생성한 전체 출력 토큰 수
#
# - estimated_usd:
#   토큰 사용량을 기준으로 계산한 예상 비용
#
# [주의]
# cached_tokens는 input_tokens에 이미 포함되어 있다.
# 전체 토큰 수에 다시 더하면 중복 계산된다.
#
# 0: 실제로 측정된 값이 0
# None/null: 값이 없거나 측정하지 못함
#
# [출력]
# observations.csv에 저장할 표 데이터

def project_rows(runs):
    rows = table_rows(runs)
    return rows


# ============================================================
# [3단계] 전체 실행 결과 요약
# ============================================================
# 함수: project_summary(runs)
#
# [목적]
# 질문별 실행 결과를 종합하여 전체 실행 상태를 확인한다.
#
# [입력]
# runs: H01~H03의 실행 기록
#
# [처리]
# summarize_runs()가 결과를 모아 요약한다.
#
# [반드시 구분할 실행 유형]
#
# ① api_live
#    실제 OpenAI API를 호출한 결과
#
# ② simulated
#    실제 API 호출 없이 모의로 실행한 결과
#
# ③ app_cache
#    이전에 생성하고 승인한 답변을 재사용한 결과
#
# ④ not_run
#    API 요청을 실행하지 않은 결과
#
# 예시:
# 실제 API 응답에 2초가 걸렸고,
# 모의 실행에 0.5초가 걸렸다고 해서
# 모의 실행이 실제 모델보다 빠르다고 판단할 수는 없다.
#
# 실제 측정값과 모의값은 구분해야 한다.
#
# 또한 질문 3개만으로 특정 모델이 항상 더 좋다고
# 결론 내릴 수는 없다.
#
# [출력]
# summary.json에 저장할 전체 실행 요약

def project_summary(runs):
    return summarize_runs(runs)


# ============================================================
# [4단계] 최종 안전 조건 확인
# ============================================================
# 함수: check_project(runs)
#
# [목적]
# 자동검사와 사람의 검토를 구분하고,
# API 호출 횟수가 허용 범위를 넘지 않았는지 확인한다.
#
# [검사 1] evidence_ok is None
#
# evidence_ok는 사람이 답변의 근거를 검토했는지 나타낸다.
#
# 예시:
# AI 답변:
# "불량품은 10일 후에도 무료로 반품할 수 있습니다."
#
# 프로그램은 JSON 형식이나 출처 번호가 올바른지 검사할 수 있다.
# 그러나 실제 규정이 이 주장을 뒷받침하는지는
# 사람이 참고 자료를 읽고 판단해야 한다.
#
# 따라서 이번 실행에서 사람이 아직 검토하지 않았다면
# evidence_ok를 True로 바꾸지 않고 None으로 유지한다.
#
# 사람의 검토는 별도의 tools/review.py에서 수행한다.
#
# [검사 2] new_api_send_count <= 4
#
# 한 질문을 처리하면서 실제 API에 요청을 보낸 횟수가
# 4회를 넘지 않았는지 확인한다.
#
# 최초 요청 외에도 통신 오류 재시도나
# JSON 형식 수정 요청으로 추가 호출이 발생할 수 있기 때문이다.
#
# [경우의 수]
# 모든 조건 충족 → True 반환
# 조건 하나라도 위반 → AssertionError 발생

def check_project(runs):
    for run in runs:
        assert run.get("evidence_ok") is None
        assert run.get("new_api_send_count", 0) <= 4

    return True


# ============================================================
# [5단계] 전체 실행 시작
# ============================================================
# 함수: main()
#
# 이 함수는 실습 전체를 연결하는 출발점이다.
#
# 실행 순서:
# ① parse_args()로 실행 옵션 확인
# ② daily_project()로 질문별 처리
# ③ check_project()로 최종 조건 확인
#
# 아래에서는 다른 파일의 함수가 내부에서
# 어떤 과정을 수행하는지도 함께 설명한다.

# ============================================================
# [5단계] 전체 실행 흐름 — daily_project() 내부 처리 과정
# ============================================================
#
# [목적]
# 질문을 준비하고 AI에게 전달한 뒤, 응답을 검증하고
# 실행 결과를 저장하는 전체 과정을 관리한다.
#
# [공통 사례]
# 질문: "상품을 받은 지 10일이 지났는데 불량품이면 반품할 수 있나요?"
# 참고 규정: "불량품은 7일 이후에도 반품 가능하며 배송비는 무료"
#
# [1. 실행 준비]
# parse_args(): 실행 옵션과 미완성 TODO를 확인한다.
# - simulated: 실제 API 호출 없이 모의 실행
# - live + allow-paid: 실제 유료 API 호출 허용
#
# [2. 질문별 처리 — daily_project() → execute_case()]
#
# ① 모델 선택 (7교시)
#    - load_settings(): 실행 환경과 사용 가능한 모델 설정 확인
#    - route()/choose_model(): fast 또는 quality에 맞는 모델 선택
#
# ② Context 구성
#    - input_parts(): 질문, 참고 지식, 답변 규칙 준비
#    - 예: 반품 질문에 필요한 반품 규정 선택
#
# ③ Prompt 조립 (2교시)
#    - build_request(): 모델, 질문, 참고 지식, 답변 규칙 결합
#    - Structured Output: API 설정에서 JSON 출력 구조 지정
#
# ④ LLM 호출 (1·3교시)
#    - run_request(): API 요청 및 응답 수신
#    - 일반 방식: 완성된 응답 수신
#    - Streaming: 텍스트를 조각별로 수신하고 TTFT 측정
#    - H01은 Streaming 방식으로 실행
#
# ⑤ 오류 처리 및 재시도 (4교시)
#    - 통신 오류: classify()로 재시도 가능 여부 판단
#    - 재시도 가능: delay()로 대기 시간 계산 후 재요청
#    - 재시도 불가능하거나 시간·횟수 초과: 중단
#    - JSON·Schema 오류: 허용 횟수 안에서 형식 수정 요청
#
# ⑥ 완료 및 출력 검사 (2교시)
#    - validate_received(): 응답 거절·완료 상태 확인
#    - JSON 구조와 출처 규칙 검사
#    - API 호출 성공과 답변 검증 성공은 별개
#
# ⑦ 측정 및 기록 (3·5교시)
#    - 응답 시간, TTFT, 입력·출력 토큰, 예상 비용 기록
#    - emit(): 성공·실패를 포함한 실행 결과를 run.json에 저장
#
# [3. 전체 결과 정리]
# project_rows(): 질문별 결과 → observations.csv
# project_summary(): 전체 실행 요약 → summary.json
# - 실제·모의·캐시·미실행 결과를 구분한다.
# - 중단된 질문도 not_run으로 기록한다.
#
# [4. 사람의 근거 검토]
# - 자동검사와 사람의 검토는 별개이다.
# - 예: AI의 반품 가능 주장이 실제 규정과 일치하는지 확인
# - 검토 전 evidence_ok = None 유지
# - 실제 사람의 검토는 tools/review.py에서 별도로 수행
#
# [5. 캐시 재사용 — 별도 실행 경로 (6교시)]
# --action reuse:
#    ① 이전 실행 결과(run.json)와 사람의 검토 기록(review.json) 확인
#    ② 승인·유효기간·출처·사용 범위 등 재사용 조건 검사
#    ③ 모든 조건 통과 → app_cache로 재사용, 새 API 호출 0회
#    ④ 조건 불충족 → cache_miss, 기존 답변 사용하지 않음
#
# --action changed:
#    - 참고 지식을 변경한 뒤 기존 캐시의 유효성 확인
#    - 캐시가 맞지 않으면 별도 실행 조건에 따라 새 API 호출
#
# ============================================================
# [6단계] main() — 전체 실행 연결
# ============================================================

def main():
    # 1. 실행 옵션과 API 호출 조건 확인
    args = parse_args(HERE)

    # 2. 질문별 처리 → API 호출·검증 → 결과 저장·요약
    runs = daily_project(
        args,
        prepare_cases=project_cases,
        make_table=project_rows,
        finish_summary=project_summary
    )

    # 3. 일반 실행 결과의 사람 미검토 상태와 API 호출 상한 확인
    if isinstance(runs, list):
        check_project(runs)


# ============================================================
# [7단계] 프로그램 시작
# ============================================================
# 직접 실행하면 main()을 시작한다.
# guarded()는 설정 오류 등을 처리해 안전하게 종료하도록 돕는다.

if __name__ == "__main__":
    guarded(main)